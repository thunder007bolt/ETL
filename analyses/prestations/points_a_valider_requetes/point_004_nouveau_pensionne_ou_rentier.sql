-- Requête : les entrées de chaque tableau de T42 à T49, de 2020 à 2025 :
--   personnes saisies, première fois, notifiées.
-- Reprise de : lot7_nouveaux_beneficiaires.sql, P82 (exécutée le 01/11/2026).
-- Base : USER_DWH, la copie du 02/02/2026, comme les lots. SQL Developer, mode
--   script (F5). Comptages seulement, aucune donnée nominative.
-- Règle appliquée dans : t42_t49_requete_proposee.sql, blocs pe, premiere et
--   entree (la première prestation de la personne dans le tableau, à sa
--   saisie). Fiche des règles : règle 62.
